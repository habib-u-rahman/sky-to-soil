import { jsPDF } from "jspdf";
import type { FarmAnalyzeResponse, ScoredRotation } from "@/types/api";

/** The PDF is always generated in English: jsPDF's built-in fonts have no
 * Arabic-script shaping (no Nastaliq joining/reordering for Urdu), so an
 * Urdu-language PDF would render as disconnected, unreadable glyphs. This
 * is a client-side-library limitation, not a translation gap. */

const MARGIN = 14;
const PAGE_WIDTH = 210;
const PAGE_HEIGHT = 297;

function rotationLabel(rotation: ScoredRotation["rotation"]): string {
  return [rotation.Y1_kharif, rotation.Y1_rabi, rotation.Y2_kharif, rotation.Y2_rabi]
    .map((c) => c ?? "fallow")
    .join(" -> ");
}

export function generateFarmPlanPdf(data: FarmAnalyzeResponse): void {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  let y = MARGIN;

  function ensureSpace(lines = 1) {
    if (y > PAGE_HEIGHT - MARGIN - lines * 6) {
      doc.addPage();
      y = MARGIN;
    }
  }

  function heading(text: string) {
    ensureSpace(2);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(14);
    doc.text(text, MARGIN, y);
    y += 8;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
  }

  function subheading(text: string) {
    ensureSpace(2);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.text(text, MARGIN, y);
    y += 6;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10);
  }

  function paragraph(text: string) {
    const lines = doc.splitTextToSize(text, PAGE_WIDTH - MARGIN * 2);
    for (const line of lines) {
      ensureSpace();
      doc.text(line, MARGIN, y);
      y += 5;
    }
  }

  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(20);
  doc.text("Sky-to-Soil — Farm Plan", MARGIN, y);
  y += 8;
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(100);
  doc.text(
    `Location: ${data.location.lat.toFixed(4)}, ${data.location.lon.toFixed(4)}  ·  Generated: ${new Date(data.generated_at).toLocaleString()}`,
    MARGIN,
    y
  );
  doc.setTextColor(0);
  y += 10;

  if (data.warnings.length > 0) {
    subheading("Data notes");
    data.warnings.forEach((w) => paragraph(`- ${w}`));
    y += 2;
  }

  if (data.climate) {
    heading("Climate shift summary");
    const { baseline, recent, deltas } = data.climate;
    paragraph(`Baseline ${baseline.period_label}  vs  Recent ${recent.period_label}`);
    paragraph(
      `Mean daytime temperature: ${baseline.mean_tmax_c?.toFixed(1)}C -> ${recent.mean_tmax_c?.toFixed(1)}C (${(deltas.mean_tmax_c ?? 0) >= 0 ? "+" : ""}${deltas.mean_tmax_c?.toFixed(1)}C)`
    );
    paragraph(
      `Mean nighttime temperature: ${baseline.mean_tmin_c?.toFixed(1)}C -> ${recent.mean_tmin_c?.toFixed(1)}C (${(deltas.mean_tmin_c ?? 0) >= 0 ? "+" : ""}${deltas.mean_tmin_c?.toFixed(1)}C)`
    );
    paragraph(
      `Kharif rainfall: ${baseline.seasonal_rainfall_mm.kharif_mm?.toFixed(0)}mm -> ${recent.seasonal_rainfall_mm.kharif_mm?.toFixed(0)}mm`
    );
    paragraph(
      `Rabi rainfall: ${baseline.seasonal_rainfall_mm.rabi_mm?.toFixed(0)}mm -> ${recent.seasonal_rainfall_mm.rabi_mm?.toFixed(0)}mm`
    );
    paragraph(
      `Root-zone wetness: ${baseline.mean_root_zone_wetness?.toFixed(2)} -> ${recent.mean_root_zone_wetness?.toFixed(2)}`
    );
    y += 2;
  }

  if (data.soil) {
    heading("Soil profile");
    if (data.soil.status !== "ok") {
      paragraph(`Status: ${data.soil.status} — ${data.soil.message ?? ""}`);
    }
    data.soil.layers.forEach((layer) => {
      paragraph(
        `${layer.depth}: pH ${layer.phh2o ?? "—"}, clay ${layer.clay_pct ?? "—"}%, sand ${layer.sand_pct ?? "—"}%, silt ${layer.silt_pct ?? "—"}%, SOC ${layer.soc_g_kg ?? "—"} g/kg, N ${layer.nitrogen_g_kg ?? "—"} g/kg, CEC ${layer.cec_cmol_kg ?? "—"} cmol/kg`
      );
    });
    y += 2;
  }

  if (data.rotations) {
    heading("Top rotations");
    paragraph(`${data.rotations.candidates_evaluated} candidate rotations evaluated for this farm.`);
    y += 1;
    data.rotations.top.slice(0, 10).forEach((r, i) => {
      ensureSpace(3);
      subheading(`${i + 1}. ${rotationLabel(r.rotation)}`);
      paragraph(
        `Score: ${r.priority_weighted_score_0_100.toFixed(0)}/100  (water ${r.sub_scores.water_fit.toFixed(0)}, heat ${r.sub_scores.heat_risk.toFixed(0)}, soil ${r.sub_scores.soil_health.toFixed(0)}, suitability ${r.sub_scores.soil_suitability.toFixed(0)})`
      );
      r.reasons.forEach((reason) => paragraph(`+ ${reason}`));
      r.warnings.forEach((warning) => paragraph(`! ${warning}`));
      y += 2;
    });
  }

  ensureSpace(2);
  doc.setFontSize(8);
  doc.setTextColor(140);
  paragraph(
    "Advisory only. Generated by Sky-to-Soil using NASA POWER, MODIS (ORNL DAAC) and ISRIC SoilGrids data. Always confirm with a local agronomist before changing your planting plan."
  );

  doc.save(`sky-to-soil-farm-plan-${data.location.lat.toFixed(2)}-${data.location.lon.toFixed(2)}.pdf`);
}
